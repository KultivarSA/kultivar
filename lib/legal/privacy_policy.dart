## Security

- Local data sits in an encrypted Hive box on your device. The
  encryption key is stored in the platform's secure storage (iOS
  Keychain, Android Keystore).
- Backup exports are wrapped in an additional AES-256-GCM envelope
  with a PBKDF2-HMAC-SHA256 derived key — your backup passphrase is
  never stored or transmitted.
- Community submissions travel to Supabase over HTTPS.

No system is perfectly secure. We use the best practices available to
the Flutter / Dart ecosystem at the time of release, and we patch
identified weaknesses promptly in subsequent updates.

