## Your rights

Because the bulk of your data lives only on your device, you control
it directly:

- **View your data** — open the app; everything is browsable.
- **Export your data** — *Settings → Backup → Export Backup* writes
  every plant, note, harvest log, and photo to an encrypted ZIP you
  can store wherever you like.
- **Delete your data** — uninstall the app, or use *Settings → Clear
  all data* to wipe everything in place.
- **Stop sharing community data** — toggle *Settings → Community →
  Share anonymous grow data* off. New submissions will not be made.
  Past submissions cannot be tied back to you and therefore cannot
  be individually deleted.

If you're a resident of the EU (GDPR) or California (CCPA), you have
additional rights to data portability, correction, and deletion. The
export + clear-all flows above already cover portability and deletion
end-to-end for the local data. For community submissions, the
anonymisation means there is no record to correct or delete against
your identity.

