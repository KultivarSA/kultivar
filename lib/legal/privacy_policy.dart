# Privacy Policy

**Last updated:** 29 May 2026

Kultivar is built around a single principle: **your grow data lives on
your device by default.** We don't have an account system, we don't
build profiles, and we don't sell anything to advertisers. This
document explains exactly what data the app touches, where it goes,
and what control you have over it.

---

## What we collect — and where it lives

### Data that stays on your device

Everything you log inside Kultivar — plants, grow spaces, photos,
notes, watering schedules, environment readings, harvest weights,
expenses, training records — is stored **locally on your device only**
in an encrypted Hive database.

We do not have a copy of this data. We can't see it, can't recover it
if your device is lost, and can't share it with anyone.

### Optional anonymous community data

If you opt into the **community benchmark** feature
(*Settings → Community → Share anonymous grow data*), Kultivar uploads
the following to our community database (Supabase):

- Strain name (normalised — lowercase, trimmed)
- Dry weight in grams
- Total grow days, vegetative days, flowering days
- Whether the plant was an autoflower or a clone
- Optional growing medium / light type / training techniques
- App version (for sample bucketing)

We **do not** upload:

- Your name, email, or any account identifier (we have none)
- Photos
- Notes
- Personal observations
- IP address (Supabase logs request IPs at the infrastructure layer
  but Kultivar's application code does not store or correlate them
  with submissions)
- Device identifiers

Each submission is independent. There is no link between two
submissions from the same device. You can switch the opt-in off at any
time; we have no way of identifying *your* past submissions to delete
them on request because they aren't tied to you.

### Subscription data (RevenueCat)

If you purchase Kultivar Pro Cloud or Lifetime Local, the App Store /
Play Store handles the transaction. Kultivar uses
[RevenueCat](https://www.revenuecat.com) — a subscription
infrastructure provider — to validate your entitlement on each device
and to support "Restore Purchases".

RevenueCat receives:

- An anonymous device identifier generated by the store
- Your subscription product ID and renewal status

RevenueCat **does not** receive any of your grow data. See
[RevenueCat's privacy policy](https://www.revenuecat.com/privacy/) for
how they handle the identifiers we send.

### Optional crash reports (Sentry)

Production builds of Kultivar may ship with crash reporting enabled
via [Sentry](https://sentry.io). When the app crashes or hits an
unhandled error, Sentry receives:

- The error name + stack trace
- The operation that failed (e.g. `StorageService.savePlants`)
- App version + OS version
- Anonymous, randomly-generated installation ID

Sentry **does not** receive any of your grow data, photo files, or
notes.

If you'd prefer not to send crash reports at all, build Kultivar
yourself from source without supplying the `SENTRY_DSN` build flag —
see `BUILD.md` in the project repository.

### Weather data (Open-Meteo)

When you enable the outdoor weather card for a grow space, Kultivar
calls [Open-Meteo](https://open-meteo.com) — a free public weather API
— with the latitude + longitude you set for that space (or that you
allow the app to detect via your device's location services).

The latitude / longitude is **only** sent to Open-Meteo at the moment
the card is being refreshed. It is not stored on any of our servers
(we don't have any servers in that loop). Open-Meteo's privacy stance
is documented at [open-meteo.com/en/terms](https://open-meteo.com/en/terms).

You can revoke the location permission from your operating system
settings at any time; the card will fall back to showing a "Set
location manually" prompt.

