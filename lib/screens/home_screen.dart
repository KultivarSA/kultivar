class _PlantRow extends StatelessWidget {
  final Plant plant;
  final List<Plant>? siblings;

  const _PlantRow({required this.plant, this.siblings});

  void _showCareSheet(
    BuildContext context,
    Plant plant,
    CareStatus waterStatus,
    CareStatus feedStatus,
    CareStatus ipmStatus,
  ) {
    final items = <({String label, IconData icon, Color color, CareStatus status})>[];
    if (plant.wateringReminderEnabled) {
      items.add((
        label: 'Watering',
        icon: Icons.water_drop_rounded,
        color: AppColors.water,
        status: waterStatus,
      ));
    }
    if (plant.feedingReminderEnabled) {
      items.add((
        label: 'Feeding',
        icon: Icons.eco_rounded,
        color: AppColors.accent,
        status: feedStatus,
      ));
    }
    if (plant.ipmReminderEnabled) {
      items.add((
        label: 'IPM Spray',
        icon: Icons.bug_report_rounded,
        color: AppColors.ipmColor,
        status: ipmStatus,
      ));
    }

    showModalBottomSheet<void>(
      context: context,
      backgroundColor: Colors.transparent,
      builder: (ctx) => AppSheet(
        title: plant.name,
        subtitle: 'Care status',
        children: [
            ...items.map((item) {
              final statusLabel = switch (item.status) {
                CareStatus.overdue  => 'Overdue',
                CareStatus.dueSoon  => 'Due soon',
                CareStatus.ok       => 'On track',
              };
              final statusColor = switch (item.status) {
                CareStatus.overdue  => AppColors.danger,
                CareStatus.dueSoon  => AppColors.warning,
                CareStatus.ok       => AppColors.primary,
              };
              return Padding(
                padding: const EdgeInsets.only(bottom: AppSpacing.sm),
                child: Row(
                  children: [
                    Container(
                      width: 32, height: 32,
                      decoration: BoxDecoration(
                        color: item.color.withValues(alpha: 0.12),
                        borderRadius:
                            BorderRadius.circular(AppSpacing.radiusSm),
                      ),
                      child:
                          Icon(item.icon, size: 15, color: item.color),
                    ),
                    const SizedBox(width: AppSpacing.sm),
                    Expanded(
                      child: Text(item.label,
                          style: AppTypography.bodyMedium(ctx)),
                    ),
                    Container(
                      padding: const EdgeInsets.symmetric(
                          horizontal: 8, vertical: 3),
                      decoration: BoxDecoration(
                        color: statusColor.withValues(alpha: 0.12),
                        borderRadius: BorderRadius.circular(
                            AppSpacing.radiusFull),
                      ),
                      child: Text(
                        statusLabel,
                        style: AppTypography.labelSmall(ctx).copyWith(
                            color: statusColor, fontSize: 11),
                      ),
                    ),
                  ],
                ),
              );
            }),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final color = AppColors.statusColor(plant.statusLabel);
    final needsBurp = plant.status == PlantStatus.curing &&
        plant.burpingRemindersEnabled;

    final repo = context.read<GrowRepository>();
    final plantNotes = repo.notesForPlant(plant.id);
    // F10 — same stage-adjusted intervals as the home reminder bell.
    final waterStatus = computeCareStatus(
      enabled: plant.wateringReminderEnabled,
      plantStatus: plant.status,
      startDate: plant.startDate,
      intervalDays: plant.effectiveWateringIntervalDays(),
      notes: plantNotes,
      plantId: plant.id,
      category: NoteCategory.watering,
    );
    final feedStatus = computeCareStatus(
      enabled: plant.feedingReminderEnabled,
      plantStatus: plant.status,
      startDate: plant.startDate,
      intervalDays: plant.effectiveFeedingIntervalDays(),
      notes: plantNotes,
      plantId: plant.id,
      category: NoteCategory.feeding,
    );
    final ipmStatus = computeCareStatus(
      enabled: plant.ipmReminderEnabled,
      plantStatus: plant.status,
      startDate: plant.startDate,
      intervalDays: plant.effectiveIpmIntervalDays(),
      notes: plantNotes,
      plantId: plant.id,
      category: NoteCategory.ipm,
    );

    // Summarise all care statuses into one badge to avoid row crowding.
    final careStatuses = [waterStatus, feedStatus, ipmStatus];
    final anyOverdue = careStatuses.any((s) => s == CareStatus.overdue);
    final anyDueSoon = careStatuses.any((s) => s == CareStatus.dueSoon);
    final showCareBadge = anyOverdue || anyDueSoon;
    final badgeColor = anyOverdue ? AppColors.danger : AppColors.warning;

    return InkWell(
      onTap: () => Navigator.push(
        context,
        MaterialPageRoute(
          builder: (_) =>
              PlantDetailScreen(plant: plant, siblings: siblings),
        ),
      ),
      child: Container(
        padding: const EdgeInsets.symmetric(
          horizontal: AppSpacing.md,
          vertical: AppSpacing.sm,
        ),
        decoration: BoxDecoration(
          border: Border(top: BorderSide(color: context.colBorderFaint)),
        ),
        child: Row(
          children: [
            // UX9 — thumbnail-or-status avatar.  Uses the most recent
            // note photo as a rounded thumb when one exists; otherwise
            // falls back to the original status-colour disc.  The
            // status colour still bleeds through via the border so the
            // status signal isn't lost when a photo is present.
            _PlantAvatar(
              plant: plant,
              notes: plantNotes,
              statusColor: color,
            ),
            const SizedBox(width: AppSpacing.sm),

            // Name + strain
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(plant.name,
                      style: AppTypography.bodyLarge(context)
                          .copyWith(fontWeight: FontWeight.w600)),
                  Text(plant.strain, style: AppTypography.bodySmall(context)),
                ],
              ),
            ),

            // Grow stage pill — visible only for actively growing plants
            if (plant.status == PlantStatus.growing &&
                plant.growStage != null) ...[
              Container(
                margin: const EdgeInsets.only(right: AppSpacing.xs),
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: AppColors.growing.withValues(alpha: 0.12),
                  borderRadius:
                      BorderRadius.circular(AppSpacing.radiusFull),
                  border: Border.all(
                      color: AppColors.growing.withValues(alpha: 0.35)),
                ),
                child: Text(
                  plant.growStage!.shortLabel,
                  style: AppTypography.labelSmall(context)
                      .copyWith(color: AppColors.growing, fontSize: 10),
                ),
              ),
            ],

            // Phase-aware day counter
            Text(
              plant.statusDaysLabel,
              style: AppTypography.bodySmall(context)
                  .copyWith(color: context.colTextMuted),
            ),
            const SizedBox(width: AppSpacing.sm),

            // Combined care badge — tap to see per-category breakdown
            if (showCareBadge) ...[
              GestureDetector(
                onTap: () => _showCareSheet(context, plant, waterStatus,
                    feedStatus, ipmStatus),
                child: Container(
                  padding: const EdgeInsets.symmetric(
                      horizontal: 5, vertical: 2),
                  decoration: BoxDecoration(
                    color: badgeColor.withValues(alpha: 0.15),
                    borderRadius:
                        BorderRadius.circular(AppSpacing.radiusFull),
                    border: Border.all(
                        color: badgeColor.withValues(alpha: 0.4)),
                  ),
                  child: Row(
                    mainAxisSize: MainAxisSize.min,
                    children: [
                      Icon(Icons.priority_high_rounded,
                          size: 10, color: badgeColor),
                      const SizedBox(width: 2),
                      Text(
                        anyOverdue ? 'Overdue' : 'Due soon',
                        style: AppTypography.labelSmall(context).copyWith(
                            color: badgeColor, fontSize: 9),
                      ),
                    ],
                  ),
                ),
              ),
              const SizedBox(width: AppSpacing.xs),
            ],

            // Burping reminder chip — visible when curing reminders are on
            if (needsBurp) ...[
              Container(
                padding: const EdgeInsets.symmetric(
                    horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: AppColors.curing.withValues(alpha: 0.15),
                  borderRadius:
                      BorderRadius.circular(AppSpacing.radiusFull),
                  border: Border.all(
                      color: AppColors.curing.withValues(alpha: 0.4)),
                ),
                child: Row(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    const Icon(Icons.air_rounded,
                        size: 10, color: AppColors.curing),
                    const SizedBox(width: 3),
                    Text(
                      'Burp',
                      style: AppTypography.labelSmall(context)
                          .copyWith(
                              color: AppColors.curing, fontSize: 9),
                    ),
                  ],
                ),
              ),
              const SizedBox(width: AppSpacing.xs),
            ],

            StatusBadge.fromStatus(plant.statusLabel, small: true),
            const SizedBox(width: AppSpacing.xs),
            Icon(Icons.chevron_right,
                size: 16, color: context.colTextMuted),
          ],
        ),
      ),
    );
  }
}

