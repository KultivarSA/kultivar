        children: [
          // Temperature
          TextField(
            controller: tempCtrl,
            autofocus: true,
            keyboardType:
                const TextInputType.numberWithOptions(decimal: true),
            style: TextStyle(color: ctx.colTextPrimary),
            decoration: InputDecoration(
              labelText: tempUnitLabel,
              prefixIcon: const Icon(Icons.thermostat_rounded),
            ),
          ),
          const SizedBox(height: AppSpacing.sm),
          // Humidity
          TextField(
            controller: humidityCtrl,
            keyboardType:
                const TextInputType.numberWithOptions(decimal: true),
            style: TextStyle(color: ctx.colTextPrimary),
            decoration: const InputDecoration(
              labelText: 'Humidity (%)',
              prefixIcon: Icon(Icons.water_drop_rounded),
            ),
          ),
          const SizedBox(height: AppSpacing.lg),
          // Action
          SizedBox(
            width: double.infinity,
            child: ElevatedButton.icon(
              icon: const Icon(Icons.add_rounded, size: 18),
              label: const Text('Save Log'),
              style: ElevatedButton.styleFrom(
                backgroundColor: AppColors.primary,
                foregroundColor: Colors.black,
                padding: const EdgeInsets.symmetric(vertical: 14),
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(AppSpacing.radiusMd),
                ),
              ),
              onPressed: () {
                final rawTemp = double.tryParse(tempCtrl.text);
                final humidity = double.tryParse(humidityCtrl.text);
                if (rawTemp == null && humidity == null) return;
                repo.addEnvironmentLog(EnvironmentLog(
                  id: repo.newId(),
                  growSpaceId: widget.space.id,
                  recordedAt: DateTime.now(),
                  temperature:
                      rawTemp != null ? toStorageTemp(rawTemp) : null,
                  humidity: humidity,
                ));
