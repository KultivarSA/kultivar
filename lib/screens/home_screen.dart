/// 32×32 avatar shown at the leading edge of a [_PlantRow].
///
/// When the plant has at least one note photo, the most recent one is
/// shown as a tinted thumbnail with a [statusColor] border.  When no
/// photo is on file the avatar falls back to a solid [statusColor]
