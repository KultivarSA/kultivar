class HomeScreen extends StatefulWidget {
  const HomeScreen({super.key});

  @override
  State<HomeScreen> createState() => _HomeScreenState();
}

class _HomeScreenState extends State<HomeScreen> {
  /// F9 — when non-null, the SliverList only renders space cards whose
  /// plant list contains at least one plant of this strain.  Plant
  /// counts in each card also collapse to "of strain X" so the visual
  /// matches the filter.  Cleared via the chip's close button.
  String? _strainFilter;

  @override
  Widget build(BuildContext context) {
    final repo = context.watch<GrowRepository>();

    // ── Pre-aggregate everything the home screen needs in ONE pass over
    //    each collection.  Previously each Space card re-ran an O(N)
    //    `where().toList()` per build × per space, which compounded fast
    //    on every repo notification (env log added, plant edited, etc.).
    //    Now: O(plants + spaces + envLogs), with O(1) lookups inside the
    //    SliverList builder.
    final activePlants = <Plant>[];
    final plantsBySpace = <String, List<Plant>>{};
    // F9 — collect the distinct strain pool *before* applying the filter
    // so the chooser sheet always shows every active strain (otherwise
    // selecting one strain would hide the rest from the picker).
    final activeStrainSet = <String>{};
    final filter = _strainFilter;
    for (final p in repo.plants) {
      if (p.isArchived) continue;
      if (p.strain.isNotEmpty) activeStrainSet.add(p.strain);
      if (filter != null && p.strain != filter) continue;
      activePlants.add(p);
      (plantsBySpace[p.growSpaceId] ??= <Plant>[]).add(p);
    }
    final activeStrains = activeStrainSet.toList()..sort();

    final spaceIdSet = <String>{for (final s in repo.growSpaces) s.id};
    final orphans = [
      for (final p in activePlants)
        if (!spaceIdSet.contains(p.growSpaceId)) p
    ];

    // Newest env log per space — single linear pass instead of N sorts.
    final latestLogBySpace = <String, EnvironmentLog>{};
    for (final l in repo.environmentLogs) {
      final cur = latestLogBySpace[l.growSpaceId];
      if (cur == null || l.recordedAt.isAfter(cur.recordedAt)) {
        latestLogBySpace[l.growSpaceId] = l;
      }
    }

    return Scaffold(
      body: CustomScrollView(
        slivers: [
          // ── App bar ──────────────────────────
          SliverAppBar(
            pinned: true,
            title: Row(
              children: [
                // Kultivar mark — bundled via `assets/branding/` in
                // pubspec, generated by the launcher-icon pipeline.
                // The PNG is white-on-transparent so it sits cleanly
                // against any AppBar background; tinted to the primary
                // brand green via `ColorFiltered` so the mark stays in
                // visual lockstep with the "Kultivar" wordmark next to
                // it instead of competing as a separate colour.
                // A9 — decorative-only.  The "Kultivar" wordmark
                // immediately to the right already announces the brand
                // name to screen readers; labelling the image would
                // make TalkBack/VoiceOver pronounce "Kultivar" twice
                // (once for the alt text, once for the Text widget).
                ColorFiltered(
                  colorFilter: const ColorFilter.mode(
                    AppColors.primary,
                    BlendMode.srcIn,
                  ),
                  child: Image.asset(
                    'assets/branding/icon_foreground.png',
                    width: 22,
                    height: 22,
                    fit: BoxFit.contain,
                    filterQuality: FilterQuality.medium,
                    excludeFromSemantics: true,
                  ),
                ),
                const SizedBox(width: AppSpacing.xs),
                // Bug fix v4: pin an explicit fontSize + clamp text
                // scaler so a user-elevated system text-scale (Samsung
                // "Large fonts") can't overflow the AppBar vertically.
                // 22 px matches headlineSmall in normal scale; pinning
                // the size keeps the wordmark on one line at any scale.
                MediaQuery.withClampedTextScaling(
                  maxScaleFactor: 1.0,
                  child: Text(
                    'Kultivar',
                    style: AppTypography.headlineMedium(context).copyWith(
                      color: AppColors.primary,
                      fontSize: 22,
                      height: 1.0,
                    ),
                    maxLines: 1,
                    overflow: TextOverflow.clip,
                  ),
                ),
              ],
            ),
            actions: [
              // ── Reminders bell ─────────────────
              Builder(builder: (ctx) {
                final reminders = buildHomeReminders(repo.plants, repo.notes,
                    spaces: repo.growSpaces,
                    envLogs: repo.environmentLogs);
                final urgent = reminders.where((r) => r.isUrgent).length;
                // UX10 — show the next-action label in the tooltip so a
                // long-press peek surfaces "Water Blue Dream · 2 more"
                // without opening the full sheet.  Single-tap behaviour
                // (open sheet) is unchanged so users who know what
                // they're doing don't pay the peek cost.
                final tooltip = reminders.isEmpty
                    ? 'Reminders'
                    : (reminders.length == 1
                        ? reminders.first.peekLabel
                        : '${reminders.first.peekLabel} · '
                            '${reminders.length - 1} more');
                return Stack(
                  alignment: Alignment.center,
                  children: [
                    IconButton(
                      icon: Icon(Icons.notifications_outlined,
                          color: urgent > 0
                              ? AppColors.warning
                              : context.colTextSecondary),
                      tooltip: tooltip,
                      onPressed: () => _showRemindersSheet(
                          ctx, repo.plants, repo.notes,
                          spaces: repo.growSpaces,
                          envLogs: repo.environmentLogs),
                    ),
                    if (urgent > 0)
                      Positioned(
                        top: 8,
                        right: 8,
                        child: Container(
                          width: 16,
                          height: 16,
                          decoration: const BoxDecoration(
                            color: AppColors.warning,
                            shape: BoxShape.circle,
                          ),
                          child: Center(
                            child: Text(
                              urgent > 9 ? '9+' : '$urgent',
                              style: const TextStyle(
                                  fontSize: 9,
                                  fontWeight: FontWeight.bold,
                                  color: Colors.black),
                            ),
                          ),
                        ),
                      ),
                  ],
                );
              }),
              // Bug fix v4: Marco flagged the Home AppBar as still
              // too crowded.  Calendar + Notes were the heaviest
              // secondary-nav items.  Moved both to the Analytics
              // AppBar where there's clearly room.  Home AppBar now
              // holds only: bell, strain-filter (conditional),
              // search, settings, chip (conditional).
              // F9 — strain-filter chip.  Hidden when only zero or one
              // strain is in active rotation (filter would be a no-op).
              if (activeStrains.length > 1)
                IconButton(
                  icon: Icon(
                    Icons.science_rounded,
                    color: _strainFilter != null
                        ? AppColors.primary
                        : context.colTextSecondary,
                  ),
                  tooltip: _strainFilter != null
                      ? 'Filter: $_strainFilter'
                      : 'Filter by strain',
                  onPressed: () => _showStrainFilterSheet(context,
                      activeStrains),
                ),
              IconButton(
                icon: Icon(Icons.search_rounded,
                    color: context.colTextSecondary),
                tooltip: 'Search',
                onPressed: () => Navigator.push(
                  context,
                  MaterialPageRoute(
                    builder: (_) => const SearchScreen(),
                  ),
                ),
              ),
              // Bug fix v2: Settings moved off the bottom nav and into
              // the AppBar (gear icon).  Placed last so it's the
              // rightmost item -- standard Material convention.
              IconButton(
                icon: Icon(Icons.settings_rounded,
                    color: context.colTextSecondary),
                tooltip: 'Settings',
                onPressed: () => Navigator.push(
                  context,
                  MaterialPageRoute(
                    builder: (_) => const SettingsScreen(),
                  ),
                ),
              ),
              // Active plant count badge.
              //
              // Bug fix v2: when the strain-filter icon is also
              // present (>1 active strain), the AppBar carries 5
              // actions + this chip + the wordmark -- which
              // overflows the S22 by 9 px.  Hide the chip in that
              // case; the same information lives in the Home grid
              // header anyway.
              if (activePlants.isNotEmpty && activeStrains.length <= 1)
                Container(
                  margin: const EdgeInsets.only(right: AppSpacing.sm),
                  padding:
                      const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                  decoration: BoxDecoration(
                    color: AppColors.primary.withValues(alpha: 0.12),
                    borderRadius: BorderRadius.circular(AppSpacing.radiusFull),
                    border: Border.all(
                        color: AppColors.primary.withValues(alpha: 0.3)),
                  ),
                  child: Text(
                    // F11 — ICU plural; resolves to "1 active",
                    // "3 active", "1 activa", "3 aktiv", etc.
                    AppLocalizations.of(context)
                        .homeActivePlants(activePlants.length),
                    style: AppTypography.labelSmall(context)
                        .copyWith(color: AppColors.primary),
                  ),
                ),
            ],
          ),

          if (repo.growSpaces.isEmpty)
            // A6 — distinguish "still loading from disk" from
            // "truly empty new install".  When the initial repo
            // load() hasn't finished, render shimmer skeleton cards
            // (perceived snappier than flashing the empty-state
            // hero then re-rendering to populated data 100 ms
            // later).  Once load() settles, fall through to either
            // the populated grid (data found) or the empty-state
            // hero (genuinely no spaces yet).
            if (repo.isLoading)
              SliverList(
                delegate: SliverChildBuilderDelegate(
                  (_, __) => const SkeletonSpaceCard(),
                  childCount: 3,
                ),
              )
            else
              const SliverFillRemaining(
                child: _HomeEmptyState(),
              )
          else ...[
            // F9 — active strain-filter banner.  Mirrors the chip in
            // the app bar but gives a one-tap "Clear" target that
            // doesn't require remembering which icon toggles it.
            if (_strainFilter != null)
              SliverToBoxAdapter(
                child: Container(
                  margin: const EdgeInsets.fromLTRB(
                      AppSpacing.pagePadding,
                      AppSpacing.xs,
                      AppSpacing.pagePadding,
                      AppSpacing.xs),
                  padding: const EdgeInsets.symmetric(
                      horizontal: AppSpacing.sm, vertical: 6),
                  decoration: BoxDecoration(
                    color: AppColors.primary.withValues(alpha: 0.08),
                    borderRadius:
                        BorderRadius.circular(AppSpacing.radiusFull),
                    border: Border.all(
                        color: AppColors.primary.withValues(alpha: 0.3)),
                  ),
                  child: Row(children: [
                    const Icon(Icons.science_rounded,
                        size: 14, color: AppColors.primary),
                    const SizedBox(width: AppSpacing.xs),
                    Expanded(
                      child: Text(
                        'Filtering by strain: $_strainFilter',
                        style: AppTypography.labelSmall(context)
                            .copyWith(color: AppColors.primary),
                      ),
                    ),
                    InkWell(
                      onTap: () => setState(() => _strainFilter = null),
                      borderRadius: BorderRadius.circular(12),
                      child: const Padding(
                        padding: EdgeInsets.all(2),
                        child: Icon(Icons.close_rounded,
                            size: 14, color: AppColors.primary),
                      ),
                    ),
                  ]),
                ),
              ),
            // ── Open issues banner ────────────────
            SliverToBoxAdapter(
              child: OpenIssuesBanner(
                plants: repo.plants,
                allNotes: repo.notes,
                repo: repo,
                onPlantTap: (plant) => Navigator.push(
                  context,
                  MaterialPageRoute(
                    builder: (_) => PlantDetailScreen(plant: plant),
                  ),
                ),
              ),
            ),

            // ── Orphaned-plant safety net ─────────
            // Catches any non-archived plant whose growSpaceId no longer
            // matches an existing space (e.g. data imported from backup).
            // Uses the orphans list precomputed at the top of build —
            // saves an O(plants) scan + Set-allocation per rebuild.
            Builder(builder: (context) {
              if (orphans.isEmpty) return const SliverToBoxAdapter();
              return SliverToBoxAdapter(
                child: Padding(
                  padding: const EdgeInsets.fromLTRB(
                    AppSpacing.pagePadding,
                    0,
                    AppSpacing.pagePadding,
                    AppSpacing.md,
                  ),
                  child: Container(
                    padding: const EdgeInsets.all(AppSpacing.md),
                    decoration: BoxDecoration(
                      color: AppColors.warning.withValues(alpha: 0.08),
                      borderRadius:
                          BorderRadius.circular(AppSpacing.radiusMd),
                      border: Border.all(
                          color: AppColors.warning.withValues(alpha: 0.35)),
                    ),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Row(children: [
                          const Icon(Icons.warning_amber_rounded,
                              color: AppColors.warning, size: 18),
                          const SizedBox(width: AppSpacing.xs),
                          Text(
                            'Unassigned Plants (${orphans.length})',
                            style: AppTypography.labelLarge(context)
                                .copyWith(color: AppColors.warning),
                          ),
                        ]),
                        const SizedBox(height: AppSpacing.xs),
                        Text(
                          "These plants' grow space no longer exists. "
                          'Tap a plant to reassign it.',
                          style: AppTypography.bodySmall(context)
                              .copyWith(color: context.colTextSecondary),
                        ),
                        const SizedBox(height: AppSpacing.sm),
                        ...orphans.map((plant) {
                          final color =
                              AppColors.statusColor(plant.statusLabel);
                          return GestureDetector(
                            onTap: () => Navigator.push(
                              context,
                              MaterialPageRoute(
                                builder: (_) =>
                                    PlantDetailScreen(plant: plant),
                              ),
                            ),
                            child: Container(
                              margin: const EdgeInsets.only(
                                  bottom: AppSpacing.xs),
                              padding: const EdgeInsets.symmetric(
                                horizontal: AppSpacing.sm,
                                vertical: AppSpacing.xs,
                              ),
                              decoration: BoxDecoration(
                                color: context.colSurface2,
                                borderRadius: BorderRadius.circular(
                                    AppSpacing.radiusSm),
                                border: Border.all(
                                    color: color.withValues(alpha: 0.3)),
                              ),
                              child: Row(children: [
                                Container(
                                  width: 6,
                                  height: 6,
                                  margin: const EdgeInsets.only(
                                      right: AppSpacing.xs),
                                  decoration: BoxDecoration(
                                      shape: BoxShape.circle, color: color),
                                ),
                                Expanded(
                                  child: Text(
                                    '${plant.name} · ${plant.statusLabel}',
                                    style:
                                        AppTypography.bodyMedium(context),
                                  ),
                                ),
                                Icon(Icons.chevron_right,
                                    size: 14,
                                    color: context.colTextMuted),
                              ]),
                            ),
                          );
                        }),
                      ],
                    ),
                  ),
                ),
              );
            }),

            SliverPadding(
              padding: const EdgeInsets.all(AppSpacing.pagePadding),
              sliver: SliverList(
                delegate: SliverChildBuilderDelegate(
                  (_, i) {
                    final space = repo.growSpaces[i];
                    // O(1) lookups instead of per-space O(N) scans —
                    // see the pre-aggregation block at the top of build.
                    final plants = plantsBySpace[space.id] ?? const <Plant>[];
                    final latest = latestLogBySpace[space.id];

                    return Padding(
                      padding: const EdgeInsets.only(bottom: AppSpacing.md),
                      child: _SpaceCard(
                        // PageStorageKey preserves _expanded state across
                        // list rebuilds triggered by repo changes.
                        key: PageStorageKey(space.id),
                        space: space,
                        plants: plants,
                        latestTemp: latest?.temperature,
                        latestHumidity: latest?.humidity,
                        // isOptimalAvailable returns null when readings are
                        // absent, true/false otherwise — cleanly separates
                        // "no data" from "out of range".
                        isOptimal: space.isOptimalAvailable(
                            latest?.temperature, latest?.humidity),
                        latestRecordedAt: latest?.recordedAt,
                      ),
                    );
                  },
                  childCount: repo.growSpaces.length,
                ),
              ),
            ),
          ],  // closes else ...[
        ],    // closes slivers: [
      ),
    );
  }

  // ── F9 — strain filter chooser ────────────────

  void _showStrainFilterSheet(BuildContext context, List<String> strains) {
    showModalBottomSheet<void>(
      context: context,
      backgroundColor: context.colSurface2,
      shape: const RoundedRectangleBorder(
        borderRadius:
            BorderRadius.vertical(top: Radius.circular(AppSpacing.radiusXl)),
      ),
      builder: (ctx) => SafeArea(
        child: ConstrainedBox(
          constraints: BoxConstraints(
            maxHeight: MediaQuery.of(ctx).size.height * 0.6,
          ),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Padding(
                padding: const EdgeInsets.fromLTRB(
                    AppSpacing.pagePadding,
                    AppSpacing.md,
                    AppSpacing.pagePadding,
                    AppSpacing.xs),
                child: Row(children: [
                  const Icon(Icons.science_rounded,
                      color: AppColors.primary, size: 20),
                  const SizedBox(width: AppSpacing.sm),
                  Text('Filter by strain',
                      style: AppTypography.headlineMedium(ctx)),
                ]),
              ),
              Padding(
                padding: const EdgeInsets.symmetric(
                    horizontal: AppSpacing.pagePadding),
                child: Text(
                  'Only show grow spaces whose plants include this strain. '
                  'Useful for comparing same-strain runs side-by-side.',
                  style: AppTypography.bodySmall(ctx)
                      .copyWith(color: ctx.colTextMuted),
                ),
              ),
              const SizedBox(height: AppSpacing.sm),
              Divider(color: ctx.colBorderFaint, height: 1),
              Flexible(
                child: ListView(
                  shrinkWrap: true,
                  children: [
                    // "All strains" sentinel resets the filter.
                    ListTile(
                      leading: Icon(Icons.clear_all_rounded,
                          color: _strainFilter == null
                              ? AppColors.primary
                              : ctx.colTextMuted),
                      title: Text('All strains',
                          style: AppTypography.labelLarge(ctx)),
                      trailing: _strainFilter == null
                          ? const Icon(Icons.check_rounded,
                              color: AppColors.primary, size: 20)
                          : null,
                      onTap: () {
                        setState(() => _strainFilter = null);
                        Navigator.pop(ctx);
                      },
                    ),
                    for (final s in strains)
                      ListTile(
                        leading: const Icon(Icons.eco_rounded,
                            color: AppColors.growing),
                        title:
                            Text(s, style: AppTypography.labelLarge(ctx)),
                        trailing: _strainFilter == s
                            ? const Icon(Icons.check_rounded,
                                color: AppColors.primary, size: 20)
                            : null,
                        onTap: () {
                          setState(() => _strainFilter = s);
                          Navigator.pop(ctx);
                        },
                      ),
                  ],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

  // ── Reminder logic ────────────────────────────
  //
  // Lives in [buildHomeReminders] (utils/home_reminders.dart) so the
  // logic is unit-testable and reusable from other surfaces.  The
  // home screen no longer owns the rules — it just renders them.

  void _showRemindersSheet(
    BuildContext context,
    List<Plant> plants,
    List<PlantNote> notes, {
    List<GrowSpace> spaces = const [],
    List<EnvironmentLog> envLogs = const [],
  }) {
    final reminders = buildHomeReminders(plants, notes,
        spaces: spaces, envLogs: envLogs);
    showModalBottomSheet<void>(
      context: context,
      isScrollControlled: true,
      backgroundColor: context.colSurface1,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(
            top: Radius.circular(AppSpacing.radiusLg)),
      ),
      builder: (ctx) => DraggableScrollableSheet(
        expand: false,
        initialChildSize: reminders.isEmpty ? 0.35 : 0.55,
        maxChildSize: 0.85,
        minChildSize: 0.3,
        builder: (_, controller) => Column(
          children: [
            // Handle
            Container(
              margin: const EdgeInsets.only(top: 10, bottom: 6),
              width: 36,
              height: 4,
              decoration: BoxDecoration(
                color: ctx.colBorder,
                borderRadius: BorderRadius.circular(AppSpacing.radiusFull),
              ),
            ),
            // Header
            Padding(
              padding: const EdgeInsets.symmetric(
                  horizontal: AppSpacing.pagePadding, vertical: AppSpacing.sm),
              child: Row(
                children: [
                  const Icon(Icons.notifications_rounded,
                      color: AppColors.primary, size: 20),
                  const SizedBox(width: AppSpacing.xs),
                  Text('Reminders',
                      style: AppTypography.headlineMedium(ctx)),
                  const Spacer(),
                  if (reminders.isNotEmpty)
                    Container(
                      padding: const EdgeInsets.symmetric(
                          horizontal: 8, vertical: 2),
                      decoration: BoxDecoration(
                        color: AppColors.warning.withValues(alpha: 0.15),
                        borderRadius:
                            BorderRadius.circular(AppSpacing.radiusFull),
                      ),
                      child: Text(
                        '${reminders.length}',
                        style: AppTypography.labelSmall(ctx)
                            .copyWith(color: AppColors.warning),
                      ),
                    ),
                ],
              ),
            ),
            const Divider(height: 1),
            // Content
            Expanded(
              child: reminders.isEmpty
                  ? Center(
                      child: Column(
                        mainAxisSize: MainAxisSize.min,
                        children: [
                          Icon(Icons.check_circle_outline_rounded,
                              size: 44, color: ctx.colTextMuted),
                          const SizedBox(height: AppSpacing.sm),
                          Text('All clear!',
                              style: AppTypography.headlineSmall(ctx)),
                          const SizedBox(height: AppSpacing.xs),
                          Text(
                            'No upcoming or overdue events\nwithin the next 7 days.',
                            textAlign: TextAlign.center,
                            style: AppTypography.bodySmall(ctx)
                                .copyWith(color: ctx.colTextMuted),
                          ),
                        ],
                      ),
                    )
                  : ListView.separated(
                      controller: controller,
                      padding: const EdgeInsets.symmetric(
                          horizontal: AppSpacing.pagePadding,
                          vertical: AppSpacing.sm),
                      itemCount: reminders.length,
                      separatorBuilder: (_, __) =>
                          Divider(height: 1, color: ctx.colBorder),
                      itemBuilder: (ctx2, idx) {
                        final r = reminders[idx];
                        return Padding(
                          padding:
                              const EdgeInsets.symmetric(vertical: AppSpacing.sm),
                          child: Row(
                            children: [
                              Container(
                                width: 36,
                                height: 36,
                                decoration: BoxDecoration(
                                  color:
                                      r.color.withValues(alpha: 0.15),
                                  borderRadius: BorderRadius.circular(
                                      AppSpacing.radiusMd),
                                ),
                                child: Icon(r.icon,
                                    size: 18, color: r.color),
                              ),
                              const SizedBox(width: AppSpacing.sm),
                              Expanded(
                                child: Column(
                                  crossAxisAlignment:
                                      CrossAxisAlignment.start,
                                  children: [
                                    Text(
                                      r.plantName,
                                      style: AppTypography.labelLarge(ctx2)
                                          .copyWith(fontSize: 13),
                                    ),
                                    Text(
                                      r.message,
                                      style:
                                          AppTypography.bodySmall(ctx2)
                                              .copyWith(
                                                  color: r.isUrgent
                                                      ? r.color
                                                      : ctx2.colTextSecondary),
                                    ),
                                  ],
                                ),
                              ),
                              if (r.isUrgent)
                                Container(
                                  padding: const EdgeInsets.symmetric(
                                      horizontal: 6, vertical: 2),
                                  decoration: BoxDecoration(
                                    color:
                                        r.color.withValues(alpha: 0.15),
                                    borderRadius: BorderRadius.circular(
                                        AppSpacing.radiusFull),
                                  ),
                                  child: Text(
                                    '!',
                                    style: AppTypography.labelSmall(ctx2)
                                        .copyWith(
                                            color: r.color,
                                            fontWeight: FontWeight.bold),
                                  ),
                                ),
                            ],
                          ),
                        );
                      },
                    ),
            ),
          ],
        ),
      ),
    );
  }
}

// Reminder logic + view-models live in lib/utils/home_reminders.dart.

// ── Space card ────────────────────────────────────

class _SpaceCard extends StatefulWidget {
  final GrowSpace space;
  final List<Plant> plants;
  final double? latestTemp;
  final double? latestHumidity;
  final bool? isOptimal;
  final DateTime? latestRecordedAt;

  const _SpaceCard({
    super.key,
    required this.space,
    required this.plants,
    this.latestTemp,
    this.latestHumidity,
