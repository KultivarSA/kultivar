class _PlantAvatar extends StatelessWidget {
  final Plant plant;
  final List<PlantNote> notes;
  final Color statusColor;

  const _PlantAvatar({
    required this.plant,
    required this.notes,
    required this.statusColor,
  });

  /// Most-recent photo filename across all of the plant's notes, or
  /// null when none exist.  Notes are already sorted newest-first by
  /// `GrowRepository.notesForPlant`, so we just take the first match.
  String? _mostRecentPhoto() {
    for (final n in notes) {
      if (n.photoUrls.isNotEmpty) return n.photoUrls.first;
    }
    return null;
  }

  @override
  Widget build(BuildContext context) {
    final photo = _mostRecentPhoto();
    // Photo path is resolved via [PhotoPathResolver] so the stored
    // filename works regardless of whether the user reinstalled (a
    // legacy absolute path stays valid; a bare filename gets prepended
    // with the current Documents directory).
    if (photo != null) {
      return Container(
        width: 32,
        height: 32,
        decoration: BoxDecoration(
          borderRadius: BorderRadius.circular(AppSpacing.radiusSm),
          // Status colour shows through as a 1.5px outer ring so the
          // signal isn't lost just because there's a thumbnail.
          border: Border.all(color: statusColor, width: 1.5),
        ),
        clipBehavior: Clip.antiAlias,
        child: Image.file(
          File(PhotoPathResolver.resolve(photo)),
          fit: BoxFit.cover,
          // P1.4 — 32 px logical thumbnail.  Without this cap a fresh
          // iPhone photo decodes at native 4032 × 3024 just to fill
          // this 32 × 32 disc.
          cacheWidth: imageCacheWidth(context, 32),
          // A9 — the plant card already announces plant name + status
          // via its surrounding Text widgets, so this 32 px thumbnail
          // is purely decorative.  Excluding it stops TalkBack from
          // injecting a redundant "image" node before the row label.
          excludeFromSemantics: true,
          // If the file vanished (manual delete, OS storage reclaim)
          // we silently degrade to the same disc fallback as no-photo.
          errorBuilder: (_, __, ___) => _StatusDisc(color: statusColor),
        ),
      );
    }
    return _StatusDisc(color: statusColor);
  }
}

/// Solid-colour rounded-square fallback used when the plant has no
/// note photos.  Slightly larger than the previous 8px dot so it
/// visually balances the rows that DO have a photo thumbnail.
class _StatusDisc extends StatelessWidget {
  final Color color;
  const _StatusDisc({required this.color});

  @override
  Widget build(BuildContext context) {
    return Container(
      width: 32,
      height: 32,
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.18),
        borderRadius: BorderRadius.circular(AppSpacing.radiusSm),
        border: Border.all(color: color, width: 1.5),
      ),
      alignment: Alignment.center,
      child: Icon(Icons.eco_rounded, size: 16, color: color),
    );
  }
}

